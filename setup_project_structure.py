def verify_dataset():
    """Verify the dataset structure and file integrity"""
    print("\n" + "="*60)
    print("VERIFYING DATASET")
    print("="*60)

    issues = []

    # Check data.yaml exists
    yaml_path = PROJECT_ROOT / "data.yaml"
    if not yaml_path.exists():
        issues.append("data.yaml not found")
    else:
        print("[OK] data.yaml exists")

    # Verify each split
    for split in ['train', 'val', 'test']:
        images_dir = PROJECT_ROOT / "dataset" / "images" / split
        labels_dir = PROJECT_ROOT / "dataset" / "labels" / split

        if not images_dir.exists():
            issues.append(f"Images directory missing: {images_dir}")
            continue

        if not labels_dir.exists():
            issues.append(f"Labels directory missing: {labels_dir}")
            continue

        # Get files
        image_files = {f.stem for f in images_dir.glob('*.jpg')} | {f.stem for f in images_dir.glob('*.png')}
        label_files = {f.stem for f in labels_dir.glob('*.txt')}

        # Check for missing labels
        missing_labels = image_files - label_files
        extra_labels = label_files - image_files

        print(f"\n{split.upper()} split:")
        print(f"  Images: {len(image_files)}")
        print(f"  Labels: {len(label_files)}")

        if missing_labels:
            print(f"  [WARNING] {len(missing_labels)} images without labels")
            issues.append(f"{split}: {len(missing_labels)} images without labels")
        else:
            print(f"  [OK] All images have labels")

        if extra_labels:
            print(f"  [WARNING] {len(extra_labels)} labels without images")
            issues.append(f"{split}: {len(extra_labels)} extra labels")

    # Print final verdict
    print("\n" + "="*60)
    if issues:
        print("[WARNING] Issues found:")
        for issue in issues:
            print(f"  - {issue}")
    else:
        print("[SUCCESS] Dataset verification passed!")
    print("="*60)


