import os
import shutil
from pathlib import Path

# =============================================================================
# CONFIGURATION
# =============================================================================

# Source dataset (Roboflow download)
SOURCE_DATASET = Path(r"F:\Research Project\Mosquito Detection Dataset.v4i.yolov11")

# Target project directory
PROJECT_ROOT = Path(r"E:\Claude local session\mosquito-detection")

# Class names from the dataset
CLASS_NAMES = ['aegypti', 'albopictus', 'anopheles', 'culex', 'culiseta', 'japonicus-koreicus']

# =============================================================================


def create_directory_structure():
    """Create the project directory structure"""
    print("\n" + "="*60)
    print("CREATING PROJECT DIRECTORY STRUCTURE")
    print("="*60)

    dirs_to_create = [
        PROJECT_ROOT,
        PROJECT_ROOT / "dataset",
        PROJECT_ROOT / "dataset" / "images",
        PROJECT_ROOT / "dataset" / "images" / "train",
        PROJECT_ROOT / "dataset" / "images" / "val",
        PROJECT_ROOT / "dataset" / "images" / "test",
        PROJECT_ROOT / "dataset" / "labels",
        PROJECT_ROOT / "dataset" / "labels" / "train",
        PROJECT_ROOT / "dataset" / "labels" / "val",
        PROJECT_ROOT / "dataset" / "labels" / "test",
        PROJECT_ROOT / "models",
        PROJECT_ROOT / "results",
    ]

    for dir_path in dirs_to_create:
        dir_path.mkdir(parents=True, exist_ok=True)
        print(f"[OK] Created: {dir_path}")

    print(f"\n[SUCCESS] Directory structure created at: {PROJECT_ROOT}")


def copy_files(source_split, target_split, file_type='images'):
    """
    Copy images or labels from source to target directory.

    Args:
        source_split: 'train', 'valid', or 'test'
        target_split: 'train', 'val', or 'test'
        file_type: 'images' or 'labels'
    """
    source_dir = SOURCE_DATASET / source_split / file_type
    target_dir = PROJECT_ROOT / "dataset" / file_type / target_split

    if not source_dir.exists():
        print(f"[WARNING] Source directory not found: {source_dir}")
        return 0

    # Get all files
    if file_type == 'images':
        files = list(source_dir.glob('*.jpg')) + list(source_dir.glob('*.png')) + list(source_dir.glob('*.jpeg'))
    else:  # labels
        files = list(source_dir.glob('*.txt'))

    if not files:
        print(f"[WARNING] No files found in: {source_dir}")
        return 0

    # Copy files
    print(f"\nCopying {len(files)} {file_type} from {source_split} to {target_split}...")

    for index, file_path in enumerate(files, start=1):
        target_path = target_dir / file_path.name
        shutil.copy2(file_path, target_path)
        print(f"  Copied {index}/{len(files)}: {file_path.name}")

    return len(files)


def reorganize_dataset():
    """Copy all images and labels to the new structure"""
    print("\n" + "="*60)
    print("COPYING DATASET FILES")
    print("="*60)

    stats = {
        'images': {'train': 0, 'val': 0, 'test': 0},
        'labels': {'train': 0, 'val': 0, 'test': 0}
    }

    # Map source splits to target splits
    # Note: Roboflow uses 'valid', we want 'val'
    split_mapping = [
        ('train', 'train'),
        ('valid', 'val'),
        ('test', 'test')
    ]

    for source_split, target_split in split_mapping:
        # Copy images
        num_images = copy_files(source_split, target_split, 'images')
        stats['images'][target_split] = num_images

        # Copy labels
        num_labels = copy_files(source_split, target_split, 'labels')
        stats['labels'][target_split] = num_labels

    # Print summary
    print("\n" + "="*60)
    print("COPY SUMMARY")
    print("="*60)

    for split in ['train', 'val', 'test']:
        img_count = stats['images'][split]
        lbl_count = stats['labels'][split]
        match = "MATCH" if img_count == lbl_count else "MISMATCH!"
        print(f"{split.upper():5s}: {img_count:5d} images, {lbl_count:5d} labels [{match}]")

    total_images = sum(stats['images'].values())
    total_labels = sum(stats['labels'].values())
    print(f"{'TOTAL':5s}: {total_images:5d} images, {total_labels:5d} labels")

    return stats


